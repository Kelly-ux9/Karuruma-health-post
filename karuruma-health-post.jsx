function useT(lang) {
  return useCallback((path) => {
    const parts = path.split(".");
    let node = DICT[lang];
    for (const p of parts) node = node?.[p];
    if (node) return node;
    let fb = DICT.en;
    for (const p of parts) fb = fb?.[p];
    return fb || path;
  }, [lang]);
}

