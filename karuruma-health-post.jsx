/* ---------------------------- date range logic ---------------------------- */
function inRange(dateStr, range, from, to) {
  const d = dateStr;
  if (range === "today") return d === todayStr();
  if (range === "yesterday") return d === daysAgoStr(1);
  if (range === "week") return d >= daysAgoStr(6) && d <= todayStr();
  if (range === "month") return d >= daysAgoStr(29) && d <= todayStr();
  if (range === "custom") return (!from || d >= from) && (!to || d <= to);
  return true; // overall
}
function computeTotals(transactions, range, from, to, extra = () => true) {
  const valid = transactions.filter((t) => t.status === "completed" && inRange(t.date, range, from, to) && extra(t));
  const cash = valid.filter((t) => t.method === "cash").reduce((s, t) => s + t.amount, 0);
  const momo = valid.filter((t) => t.method === "momo").reduce((s, t) => s + t.amount, 0);
  return { cash, momo, total: cash + momo, count: valid.length };
}

